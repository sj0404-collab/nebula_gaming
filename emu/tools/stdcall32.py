#!/usr/bin/env python3
"""Generate emu/x64/stdcall32.inc: stack bytes cleaned by 32-bit stdcall APIs (callee-cleaned), from Wine .spec files.
Usage: stdcall32.py <spec dir> <emu/x64 dir>. Only names that the shim layer mentions are kept (the table is linked into the wasm)."""
import sys, re, os, glob
spec_dir, src_dir = sys.argv[1], sys.argv[2]
known = set()
for f in glob.glob(os.path.join(src_dir, '*.c')) + glob.glob(os.path.join(src_dir, '*.inc')):
    s = open(f, encoding='utf-8', errors='replace').read()
    known |= set(re.findall(r'"([A-Za-z_][A-Za-z0-9_]*)"', s))
    known |= set(re.findall(r'\bS\(([A-Za-z_][A-Za-z0-9_]*)\)', s))
    known |= set(re.findall(r'\bSA\("([^"]+)"', s))
    known |= set(re.findall(r'\bDS\([^,]+,\s*"?([A-Za-z_][A-Za-z0-9_]*)', s))
sizes = {'long': 4, 'ptr': 4, 'str': 4, 'wstr': 4, 'int64': 8, 'double': 8, 'float': 4, 'int128': 16, 'word': 4, 'segptr': 4, 'segstr': 4}
tab = {}
for f in sorted(glob.glob(os.path.join(spec_dir, '*.spec'))):
    for line in open(f, encoding='utf-8', errors='replace'):
        m = re.match(r'^\s*(\d+|@)\s+(stdcall|cdecl|varargs|thiscall|fastcall|pascal)\s+((?:-\S+\s+)*)([A-Za-z_][A-Za-z0-9_@]*)\s*\(([^)]*)\)', line)
        if not m: continue
        conv, flags, name, args = m.group(2), m.group(3), m.group(4), m.group(5).split()
        if '-arch=win64' in flags or '-arch=x86_64' in flags or '-i386' in flags and conv != 'stdcall': continue
        if conv != 'stdcall': continue
        n = sum(sizes.get(a, 4) for a in args)
        if name in known and name not in tab: tab[name] = n
# APIs that Wine stubs/omits or that live in DLLs without a spec here (mswsock, combase): arity from the Windows SDK headers
extra = {'AcceptEx': 32, 'ConnectEx': 28, 'DisconnectEx': 16, 'GetAcceptExSockaddrs': 32, 'TransmitFile': 28, 'ProcessPrng': 8, 'SetThreadpoolWaitEx': 16,
         'RoInitialize': 4, 'RoUninitialize': 0, 'RoGetActivationFactory': 12, 'RoOriginateError': 8, 'RoOriginateErrorW': 12, 'RoOriginateLanguageException': 12,
         'RoReportUnhandledError': 4, 'RoGetErrorReportingFlags': 4, 'RoSetErrorReportingFlags': 4, 'GetRestrictedErrorInfo': 4, 'SetRestrictedErrorInfo': 4,
         'XInputGetAudioDeviceIds': 20, '_CxxThrowException': 8, '_SetWinRTOutOfMemoryExceptionCallback': 4}
for k, v in extra.items():
    if k in known: tab.setdefault(k, v)
out = ['/* generated by emu/tools/stdcall32.py from Wine .spec files — bytes of stack arguments removed by the callee (32-bit stdcall); names absent here are cdecl/varargs (caller cleans) */',
       'static const struct { const char *n; unsigned short bytes; } stdcall32_tab[] = {']
for k in sorted(tab): out.append('  { "%s", %d },' % (k, tab[k]))
out.append('};')
open(os.path.join(src_dir, 'stdcall32.inc'), 'w').write('\n'.join(out) + '\n')
print(len(tab), 'entries of', len(known), 'known names')
