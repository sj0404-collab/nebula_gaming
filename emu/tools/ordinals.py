#!/usr/bin/env python3
"""generate emu/x64/ordinals.inc: export ordinal -> name for the system DLLs whose exports programs import by number
(comctl32 #17 = InitCommonControls, shlwapi, shell32, oleaut32, ws2_32, ...) from the Wine .spec files."""
import re, sys, os
spec_dir, out_dir = sys.argv[1], sys.argv[2]
rows = []
for fn in sorted(os.listdir(spec_dir)):
    if not fn.endswith('.spec'): continue
    dll = fn[:-5].lower()
    for line in open(os.path.join(spec_dir, fn), encoding='utf-8', errors='replace'):
        m = re.match(r'^\s*(\d+)\s+(stdcall|cdecl|varargs|thiscall|fastcall|pascal)\s+((?:-\S+\s+)*)([A-Za-z_][A-Za-z0-9_@]*)\s*\(', line)
        if not m: continue
        ordn, name = int(m.group(1)), m.group(4)
        rows.append((dll, ordn, name))
# documented ordinals absent from the Wine .spec files (comctl32 v6 exports these by number as well)
rows += [('comctl32', 380, 'LoadIconMetric'), ('comctl32', 381, 'LoadIconWithScaleDown')]
rows.sort()
with open(os.path.join(out_dir, 'ordinals.inc'), 'w') as f:
    f.write('/* generated by emu/tools/ordinals.py from Wine .spec files: numbered exports of system DLLs (import by ordinal) */\n')
    f.write('static const struct { const char *dll; unsigned short ord; const char *name; } g_ordinals[] = {\n')
    for dll, o, n in rows: f.write('  { "%s", %d, "%s" },\n' % (dll, o, n))
    f.write('};\n')
print(len(rows), 'ordinals')
