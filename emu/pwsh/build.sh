#!/bin/sh
# Builds powershell.exe (freestanding, kernel32 only) and the C header the emulator embeds it with.
set -e
cd "$(dirname "$0")"
ZIG=${ZIG:-zig}
$ZIG cc -target x86_64-windows-gnu -Os -fno-builtin -fno-stack-protector -mno-stack-arg-probe -nostdlib -Wall -Wno-unused-function \
  -Wl,--subsystem,console -Wl,-e,mainCRTStartup -lkernel32 -o powershell.exe pwsh.c
python3 - <<'PY'
d = open('powershell.exe', 'rb').read()
with open('../x64/pwsh_exe.h', 'w') as f:
    f.write('/* generated by emu/pwsh/build.sh from emu/pwsh/pwsh.c — do not edit */\n')
    f.write('static const unsigned char pwsh_exe_bytes[%d] = {\n' % len(d))
    for i in range(0, len(d), 32): f.write(','.join(str(b) for b in d[i:i+32]) + ',\n')
    f.write('};\n')
PY
ls -la powershell.exe ../x64/pwsh_exe.h
